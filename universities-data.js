// ==========================================
// القائمة الفعالة للجامعات (Shared Helper)
// ترجع قائمة الجامعات المحكومة من لوحة الإدارة إن وُجدت،
// وإلا ترجع القائمة الافتراضية الثابتة أعلاه
// تُستخدم في صفحة الإدارة admin.html وبوابة الموظفين index.html
// ==========================================
function getActiveUniversities() {
  let managed = [];

  try {
    if (window.firebaseService && typeof window.firebaseService.getLocal === "function") {
      managed = window.firebaseService.getLocal("universities") || [];
    } else {
      managed = JSON.parse(localStorage.getItem("lotus_affairs_universities_data") || "[]");
    }
  } catch (e) {
    managed = [];
  }

  if (Array.isArray(managed) && managed.length > 0) {
    return managed.map(u => (u || "").toString().trim()).filter(Boolean);
  }

  return EGYPTIAN_UNIVERSITIES.slice();
}

window.getActiveUniversities = getActiveUniversities;

// القائمة الافتراضية الثابتة فقط (لأداة الاستيراد في لوحة الإدارة)
window.getStaticDefaultUniversities = function () {
  return EGYPTIAN_UNIVERSITIES.slice();
};
